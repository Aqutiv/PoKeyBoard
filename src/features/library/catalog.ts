/**
 * The built-in library, in display order. This module must stay free of
 * service imports: the persistence layer imports it to rebuild a library
 * take at startup.
 */
export const LIBRARY_TRACKS: readonly LibraryTrackDef[] = [
  A_BEAUTIFUL_DAY,
  EVENING_TIDE,
  FORWARD_GENTLY,
  CROOKED_LANTERN_WALTZ,
  FUR_ELISE,
  GYMNOPEDIE_1,
  BLUES_IN_C,
  GOOD_NIGHT,
  MOONLIGHT_SONATA,
];

export interface LibraryTrackSummary {
  trackId: string;
  takeId: string;
  title: string;
  composer: string;
  folder: LibraryFolderId;
  /**
   * 'authored' tracks are transcribed into this repo and built synchronously;
   * 'score' tracks are vendored MusicXML, fetched and parsed when opened.
   */
  source: 'authored' | 'score';
  /** Only the authored tracks carry prose; the vendored scores show none. */
  descriptionKey?: LibraryTrackDef['descriptionKey'];
  bpm: number;
  durationMs: number;
  noteCount: number;
}

/** List metadata, derived once — the list view never rebuilds full takes. */
export const LIBRARY_TRACK_SUMMARIES: readonly LibraryTrackSummary[] = LIBRARY_TRACKS.map((def) => {
  const take = buildLibraryTake(def);
  return {
    trackId: def.trackId,
    takeId: take.id,
    title: def.title,
    composer: def.composer,
    folder: def.folder,
    source: 'authored' as const,
    descriptionKey: def.descriptionKey,
    bpm: def.bpm,
    durationMs: take.durationMs,
    noteCount: take.notes.length,
  };
});

/**
 * The vendored score pack as list metadata. Nothing is fetched here: the
 * numbers come from the manifest, which was generated by parsing each score
 * once. Scores with no curated name are dropped rather than shown under a
 * filename — a unit test fails on the mismatch.
 */
const CLASSIC_SCORE_SUMMARIES: readonly LibraryTrackSummary[] = CLASSIC_SCORES.flatMap((entry) => {
  const name = CLASSIC_SCORE_NAMES[entry.trackId];
  if (!name) return [];
  return [
    {
      trackId: entry.trackId,
      takeId: libraryTakeId(entry.trackId),
      title: name.title,
      composer: name.composer,
      folder: 'classics' as const,
      source: 'score' as const,
      // Scores carry a parsed tempo, which is not always a whole number.
      bpm: Math.round(entry.bpm),
      durationMs: entry.durationMs,
      noteCount: entry.noteCount,
    },
  ];
});

function summariesIn(folder: LibraryFolderId): readonly LibraryTrackSummary[] {
  return LIBRARY_TRACK_SUMMARIES.filter((summary) => summary.folder === folder);
}

/**
 * The summaries shelved by folder, each folder keeping the catalog's display
 * order. Derived once, so the list view never filters on render; spelled out a
 * key at a time so a new folder id fails to compile until it is filed here.
 * Classics leads with the authored transcriptions, then the vendored pack.
 */
export const LIBRARY_FOLDER_SUMMARIES: Record<LibraryFolderId, readonly LibraryTrackSummary[]> = {
  originals: summariesIn('originals'),
  classics: [...summariesIn('classics'), ...CLASSIC_SCORE_SUMMARIES],
};

export interface LibrarySection {
  /** Composer heading, or null for the pinned run above the first heading. */
  composer: string | null;
  tracks: readonly LibraryTrackSummary[];
}

/**
 * Surname to file a composer under: the last word of the credit, which puts
 * "Ludwig van Beethoven" under B the way a classical index would. Every
 * credit in the catalog ends in a surname — a test holds that true.
 */
function surnameOf(composer: string): string {
  return composer.slice(composer.lastIndexOf(' ') + 1);
}

/** One section per composer, surnames in order, titles in order within each. */
function byComposer(tracks: readonly LibraryTrackSummary[]): LibrarySection[] {
  const groups = new Map<string, LibraryTrackSummary[]>();
  for (const track of tracks) {
    const group = groups.get(track.composer);
    if (group) group.push(track);
    else groups.set(track.composer, [track]);
  }
  return [...groups.entries()]
    .sort(
      ([a], [b]) => surnameOf(a).localeCompare(surnameOf(b)) || a.localeCompare(b),
      // Ties on surname fall back to the full credit, so the order is total.
    )
    .map(([composer, group]) => ({
      composer,
      tracks: group.sort((a, b) => a.title.localeCompare(b.title)),
    }));
}

/**
 * How each folder is laid out: a run of ungrouped tracks, then any composer
 * groups. Originals is six tracks and stays flat; Classics leads with the
 * authored transcriptions — the only ones carrying a description — and files
 * the vendored pack under its composers.
 */
export const LIBRARY_FOLDER_SECTIONS: Record<LibraryFolderId, readonly LibrarySection[]> = {
  originals: [{ composer: null, tracks: LIBRARY_FOLDER_SUMMARIES.originals }],
  classics: [
    { composer: null, tracks: summariesIn('classics') },
    ...byComposer(CLASSIC_SCORE_SUMMARIES),
  ],
};

/**
 * The sections narrowed to tracks matching `query`, against title and
 * composer together. Sections left with nothing drop out, so the headings
 * follow the results; the order the sections were built in is untouched.
 *
 * A blank query hands back the very same array, so the page re-renders
 * nothing while the field is empty.
 */
export function filterLibrarySections(
  sections: readonly LibrarySection[],
  query: string,
): readonly LibrarySection[] {
  if (query.trim() === '') return sections;
  return sections.flatMap((section) => {
    const tracks = section.tracks.filter((track) =>
      matchesSearch(`${track.title} ${track.composer}`, query),
    );
    return tracks.length > 0 ? [{ ...section, tracks }] : [];
  });
}

/**
 * Build a pristine `Take` for an authored library take id. A fresh object
 * every call: whatever the transport or stores did to a previous copy can
 * never leak back into the catalog.
 */
export function getLibraryTake(takeId: string): Take | undefined {
  const def = LIBRARY_TRACKS.find((entry) => libraryTakeId(entry.trackId) === takeId);
  return def ? buildLibraryTake(def) : undefined;
}

/**
 * The take behind any library id, authored or vendored. Async because a score
 * has to be fetched and parsed; it throws when the fetch fails, so callers can
 * tell an unknown track from an unreachable one. `signal` bounds that fetch —
 * authored tracks are built synchronously and ignore it.
 */
export async function resolveLibraryTake(
  takeId: string,
  signal?: AbortSignal,
): Promise<Take | undefined> {
  const authored = getLibraryTake(takeId);
  if (authored) return authored;
  if (!isLibraryTakeId(takeId)) return undefined;
  return loadClassicTake(takeId.slice(LIBRARY_ID_PREFIX.length), signal);
}
